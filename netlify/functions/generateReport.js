const PDFDocument = require("pdfkit");
const getStream = require("get-stream");
const axios = require("axios");

exports.handler = async (event) => {
  try {
    const { name, birthDate, birthTime, birthPlace } = JSON.parse(event.body);

    // Fetch NASA planetary data from nasaKP function (absolute URL for Netlify live)
    let nasaData = {};
    try {
      const baseUrl = process.env.URL || "https://sathyadarshana.netlify.app";
      const res = await axios.get(`${baseUrl}/.netlify/functions/nasaKP`);
      nasaData = res.data || {};
    } catch (e) {
      nasaData = { error: "NASA data not available" };
    }

    // Generate PDF
    const doc = new PDFDocument();
    doc.fontSize(20).text("Sathyadarshana KP Report", { align: "center" });
    doc.moveDown();
    doc.fontSize(12).text(`Full Name: ${name || "N/A"}`);
    doc.text(`Date of Birth: ${birthDate || "N/A"}`);
    doc.text(`Time of Birth: ${birthTime || "N/A"}`);
    doc.text(`Place of Birth: ${birthPlace || "N/A"}`);
    doc.moveDown();
    doc.text("Planetary Positions (NASA KP):");
    doc.text(JSON.stringify(nasaData, null, 2));
    doc.moveDown();
    doc.text("Generated by Buddhi AI", { align: "right" });

    const buffer = await getStream.buffer(doc);

    return {
      statusCode: 200,
      headers: {
        "Content-Type": "application/pdf",
        "Content-Disposition": 'attachment; filename="KP_Report.pdf"',
      },
      body: buffer.toString("base64"),
      isBase64Encoded: true,
    };
  } catch (err) {
    return {
      statusCode: 500,
      body: JSON.stringify({
        error: "Report generation failed",
        details: err.message,
      }),
    };
  }
};
